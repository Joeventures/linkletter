# Public endpoint behind every emailed personal link. Inherits from
# ActionController::Base on purpose: it must not require a login and must not
# reject older browsers or email clients the way ApplicationController does.
class RedirectsController < ActionController::Base
  TOKEN_FORMAT = /\A[1-9A-HJ-NP-Za-km-z]{32}\z/ # base58, as generated by has_secure_token

  rate_limit to: 30, within: 1.minute, by: -> { request.remote_ip },
             with: -> { head :too_many_requests }

  def show
    token = params[:token].to_s
    personal_link = PersonalLink.includes(:link).find_by(token: token) if token.match?(TOKEN_FORMAT)
    return head(:not_found) unless personal_link

    begin
      personal_link.record_click!(request)
    rescue => e
      # Never strand the recipient because tracking failed.
      Rails.logger.error("Click tracking failed for personal_link=#{personal_link.id}: #{e.class}: #{e.message}")
    end

    response.headers["Cache-Control"] = "no-store"
    response.headers["Referrer-Policy"] = "no-referrer" # don't leak the token to the destination
    response.headers["X-Robots-Tag"] = "noindex, nofollow"
    redirect_to personal_link.link.url, allow_other_host: true
  end
end
